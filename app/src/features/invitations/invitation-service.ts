import type { SupabaseClient } from "@supabase/supabase-js";
import type {
  Invitation,
  InvitationState,
  InvitationStatus,
  MemberRole,
  Result,
} from "@/lib/domain/types";

/** Roles an invitation link may grant. Admin/owner are assigned manually only. */
export type InvitableRole = Extract<
  MemberRole,
  "staff" | "creator" | "player"
>;

interface InvitationRow {
  id: string;
  token: string;
  role: MemberRole;
  status: InvitationStatus;
  created_at: string;
  expires_at: string | null;
  max_uses: number | null;
  use_count: number;
}

/** Derive the UI-facing state from status, expiry, and remaining uses. */
function deriveState(row: {
  status: InvitationStatus;
  expires_at: string | null;
  max_uses: number | null;
  use_count: number;
}): InvitationState {
  if (row.status === "revoked") return "revoked";
  if (row.status === "accepted") return "accepted";
  if (row.expires_at && new Date(row.expires_at).getTime() < Date.now()) {
    return "expired";
  }
  if (row.max_uses != null && row.use_count >= row.max_uses) {
    return "exhausted";
  }
  return "active";
}

function toInvitation(row: InvitationRow): Invitation {
  return {
    id: row.id,
    token: row.token,
    role: row.role,
    status: row.status,
    createdAt: row.created_at,
    expiresAt: row.expires_at,
    maxUses: row.max_uses,
    useCount: row.use_count,
    state: deriveState(row),
  };
}

const SELECT =
  "id, token, role, status, created_at, expires_at, max_uses, use_count";

/**
 * Invitation service — owns invitation data access: creating configurable
 * links, listing, revoking, editing, and redeeming. Single responsibility.
 */
export class InvitationService {
  constructor(private readonly supabase: SupabaseClient) {}

  /** All invitations for an org, newest first. */
  async listInvitations(orgId: string): Promise<Result<Invitation[]>> {
    const { data, error } = await this.supabase
      .from("invitations")
      .select(SELECT)
      .eq("org_id", orgId)
      .order("created_at", { ascending: false });

    if (error) return { ok: false, error: error.message };

    return {
      ok: true,
      data: (data ?? []).map((r) => toInvitation(r as InvitationRow)),
    };
  }

  /**
   * Create a configurable invitation link. The token is generated by the DB.
   * `expiresAt` null = never, `maxUses` null = unlimited.
   */
  async createInvitation(
    orgId: string,
    input: {
      role: InvitableRole;
      createdBy: string;
      expiresAt: string | null;
      maxUses: number | null;
    }
  ): Promise<Result<Invitation>> {
    const { data, error } = await this.supabase
      .from("invitations")
      .insert({
        org_id: orgId,
        role: input.role,
        created_by: input.createdBy,
        expires_at: input.expiresAt,
        max_uses: input.maxUses,
      })
      .select(SELECT)
      .single();

    if (error) return { ok: false, error: error.message };
    return { ok: true, data: toInvitation(data as InvitationRow) };
  }

  /** Update a pending invitation's role, expiry, or usage cap. */
  async updateInvitation(
    invitationId: string,
    input: {
      role: InvitableRole;
      expiresAt: string | null;
      maxUses: number | null;
    }
  ): Promise<Result<null>> {
    const { error } = await this.supabase
      .from("invitations")
      .update({
        role: input.role,
        expires_at: input.expiresAt,
        max_uses: input.maxUses,
      })
      .eq("id", invitationId);

    if (error) return { ok: false, error: error.message };
    return { ok: true, data: null };
  }

  /** Revoke a pending invitation. */
  async revokeInvitation(invitationId: string): Promise<Result<null>> {
    const { error } = await this.supabase
      .from("invitations")
      .update({ status: "revoked" })
      .eq("id", invitationId);

    if (error) return { ok: false, error: error.message };
    return { ok: true, data: null };
  }

  /** Permanently delete an invitation. Confirms a row was actually removed. */
  async deleteInvitation(invitationId: string): Promise<Result<null>> {
    const { data, error } = await this.supabase
      .from("invitations")
      .delete()
      .eq("id", invitationId)
      .select("id");

    if (error) return { ok: false, error: error.message };
    // RLS can silently delete zero rows; surface that instead of a false success.
    if (!data || data.length === 0) {
      return {
        ok: false,
        error: "No se pudo eliminar la invitación (permisos).",
      };
    }
    return { ok: true, data: null };
  }

  /** Redeem an invite token for the current user via the DB function. */
  async redeemInvitation(token: string): Promise<Result<string>> {
    const { data, error } = await this.supabase.rpc("redeem_invitation", {
      invite_token: token,
    });

    if (error) return { ok: false, error: error.message };
    return { ok: true, data: data as string };
  }
}
